import type { Table, TableGroup } from './drizzle';
import type { Procedure } from './trpc';

const REGENERATE = "Don't edit it: run `pnpm docs:generate`.";

/** Mermaid ER names: letters, digits, `_` and `-`, starting with a letter. */
function erName(name: string): string {
  const safe = name.replace(/[^\w-]/gu, '_');
  return /^[a-z]/iu.test(safe) ? safe : `t_${safe}`;
}

/** Mermaid ER attribute types allow no spaces or commas: `timestamp with time zone` → `timestamp_with_time_zone`. */
function erType(type: string): string {
  const safe = type
    .replace(/\s*,\s*/gu, '_')
    .replace(/\s+/gu, '_')
    .replace(/[^\w()[\]]/gu, '_');
  return /^[a-z]/iu.test(safe) ? safe : `t_${safe}`;
}

function attribute(table: Table, column: Table['columns'][number]): string {
  const foreign = table.foreignKeys.some((key) => key.columns.includes(column.name));
  const keys = [
    ...(column.primaryKey ? ['PK'] : []),
    ...(foreign ? ['FK'] : []),
    ...(column.unique && !column.primaryKey ? ['UK'] : []),
  ];
  const comment = column.notNull || column.primaryKey ? '' : ' "nullable"';
  return `        ${erType(column.type)} ${erName(column.name)}${keys.length > 0 ? ` ${keys.join(', ')}` : ''}${comment}`;
}

function relationships(table: Table): string[] {
  return table.foreignKeys.map((key) => {
    const optional = key.columns.some(
      (name) => table.columns.find((column) => column.name === name)?.notNull === false,
    );
    return `    ${erName(table.name)} }o--${optional ? 'o|' : '||'} ${erName(key.table)} : "${key.columns.join(', ')}"`;
  });
}

export function renderDatabase(groups: TableGroup[], sourceLink: string): string {
  const count = groups.reduce((total, group) => total + group.tables.length, 0);
  const sections = groups.map((group) => {
    const lines = ['erDiagram'];
    for (const table of group.tables) {
      lines.push(`    ${erName(table.name)} {`);
      lines.push(...table.columns.map((column) => attribute(table, column)));
      lines.push('    }');
    }
    for (const table of group.tables) lines.push(...relationships(table));
    return [`## ${group.name}`, '', '```mermaid', ...lines, '```'].join('\n');
  });
  return [
    '# Database',
    '',
    `Generated by \`doc-gen\` from ${sourceLink}. ${REGENERATE}`,
    '',
    `${count} tables in ${groups.length} ${groups.length === 1 ? 'group' : 'groups'}. Each section is one schema module; a table from another section shows by name only. Keys: PK primary, FK foreign, UK unique.`,
    '',
    ...sections.flatMap((section) => [section, '']),
  ].join('\n');
}

function procedureLine(procedure: Procedure): string {
  const input = procedure.input === undefined ? '' : ` · \`${procedure.input}\``;
  const description =
    procedure.description === undefined ? '' : `: ${procedure.description}`;
  return `- \`${procedure.path}\` · ${procedure.type}${input}${description}`;
}

export function renderApiRoutes(procedures: Procedure[], sourceLink: string): string {
  const sections = new Map<string, Procedure[]>();
  for (const procedure of procedures) {
    const name = procedure.path.includes('.')
      ? (procedure.path.split('.')[0] as string)
      : 'root';
    sections.set(name, [...(sections.get(name) ?? []), procedure]);
  }
  // Procedures at the top level come first.
  const names = [...sections.keys()].sort(
    (a, b) => Number(b === 'root') - Number(a === 'root') || a.localeCompare(b),
  );
  return [
    '# API routes',
    '',
    `Generated by \`doc-gen\` from ${sourceLink}. ${REGENERATE}`,
    '',
    `${procedures.length} procedures. Each section is one top-level router; each line is path · type · input fields (\`?\` optional): description.`,
    '',
    ...names.flatMap((name) => [
      `## ${name}`,
      '',
      ...(sections.get(name) ?? []).map(procedureLine),
      '',
    ]),
  ].join('\n');
}
